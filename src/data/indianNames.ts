let lastPickedIndex = -1;

export function getRandomIndianName(): string {
  if (INDIAN_NAMES_300.length === 0) return 'Rafik Laskar';
  let idx = Math.floor(Math.random() * INDIAN_NAMES_300.length);
  if (idx === lastPickedIndex && INDIAN_NAMES_300.length > 1) {
    idx = (idx + 1) % INDIAN_NAMES_300.length;
  }
  lastPickedIndex = idx;
  return INDIAN_NAMES_300[idx];
}
